export const RECENT_LIMIT = 24;

/**
 * Merge a usage tally into a most-used-first list.
 * @param {Record<string, number>} usage emoji -> times picked
 */
export const rankRecents = (usage = {}) =>
	Object.entries(usage)
		.sort(([, a], [, b]) => b - a)
		.slice(0, RECENT_LIMIT)
		.map(([emoji]) => emoji);
